-- Acceso al panel y auditoria.
--
-- Las cuentas no se borran: se desactivan con activo = false. Por eso todas
-- las claves foraneas hacia usuarios usan ON DELETE RESTRICT.
--
-- No incluyas BEGIN/COMMIT: migrate.php ya envuelve esta migracion.

-- ---------------------------------------------------------------------------
-- roles
-- ---------------------------------------------------------------------------
-- Solo dos roles iniciales. Los permisos finos viven en el servidor; aqui
-- solo se guarda el nombre para que la API pueda decidir.
-- ---------------------------------------------------------------------------

CREATE TABLE roles (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  text     NOT NULL UNIQUE
);

INSERT INTO roles (nombre) VALUES
    ('admin'),
    ('editor')
ON CONFLICT (nombre) DO NOTHING;

-- ---------------------------------------------------------------------------
-- usuarios
-- ---------------------------------------------------------------------------
-- password_hash guarda Argon2id, nunca la contrasena. El correo se compara
-- sin distinguir mayusculas mediante un indice sobre lower(correo), sin
-- depender de la extension citext.
--
-- intentos_fallidos y bloqueado_hasta permiten el bloqueo por cuenta. El
-- limite por correo e IP se calcula con intentos_login, no con estas columnas.
-- ---------------------------------------------------------------------------

CREATE TABLE usuarios (
    id                  bigserial   PRIMARY KEY,
    correo              text        NOT NULL,
    password_hash       text        NOT NULL,
    nombre              text        NOT NULL,
    rol_id              smallint    NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    activo              boolean     NOT NULL DEFAULT true,
    intentos_fallidos   integer     NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta     timestamptz,
    ultimo_acceso       timestamptz,
    creado_en           timestamptz NOT NULL DEFAULT now(),
    actualizado_en      timestamptz NOT NULL DEFAULT now(),

    -- Solo correos institucionales. lower() hace que la comprobacion no
    -- dependa de como haya escrito el usuario el dominio.
    CONSTRAINT usuarios_correo_dominio_check CHECK (
        lower(correo) ~ '^[^[:space:]@]+@(uleam\.edu\.ec|live\.uleam\.edu\.ec)$'
    )
);

-- Unicidad real del correo: "Admin@ULEAM.edu.ec" y "admin@uleam.edu.ec" son
-- la misma cuenta aunque se guarden con distinta capitalizacion.
CREATE UNIQUE INDEX usuarios_correo_lower_idx ON usuarios (lower(correo));

CREATE TRIGGER usuarios_actualizado_en_trg
    BEFORE UPDATE ON usuarios
    FOR EACH ROW
    EXECUTE FUNCTION marcar_actualizado_en();

-- ---------------------------------------------------------------------------
-- sesiones
-- ---------------------------------------------------------------------------
-- Autenticacion por sesion de servidor con cookie HttpOnly. La base nunca
-- guarda el token ni el token CSRF: solo su SHA-256 en hexadecimal.
--
-- revocada_en nullable permite cerrar sesion sin borrar el historial. La
-- purga puede borrar las expiradas, pero el registro se conserva hasta que
-- toque limpiarlo.
--
-- ip y user_agent son metadatos opcionales: una peticion puede no traerlos.
-- ---------------------------------------------------------------------------

CREATE TABLE sesiones (
    token_hash   text        PRIMARY KEY,
    csrf_hash    text        NOT NULL,
    usuario_id   bigint      NOT NULL REFERENCES usuarios (id) ON DELETE RESTRICT,
    expira_en    timestamptz NOT NULL,
    ip           inet,
    user_agent   text,
    creado_en    timestamptz NOT NULL DEFAULT now(),
    revocada_en  timestamptz
);

CREATE INDEX sesiones_usuario_id_idx ON sesiones (usuario_id);
CREATE INDEX sesiones_expira_en_idx ON sesiones (expira_en);

-- ---------------------------------------------------------------------------
-- intentos_login
-- ---------------------------------------------------------------------------
-- Registro de intentos para limitar por correo e IP. No lleva FK a usuarios:
-- un intento con un correo inexistente tambien cuenta para el limite.
--
-- La API debe guardar el correo en minusculas para que el indice por correo
-- agrupe las variantes de capitalizacion.
-- ---------------------------------------------------------------------------

CREATE TABLE intentos_login (
    id         bigserial   PRIMARY KEY,
    correo     text        NOT NULL,
    ip         inet        NOT NULL,
    exitoso    boolean     NOT NULL DEFAULT false,
    creado_en  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX intentos_login_correo_creado_en_idx
    ON intentos_login (correo, creado_en);

CREATE INDEX intentos_login_ip_creado_en_idx
    ON intentos_login (ip, creado_en);

-- ---------------------------------------------------------------------------
-- auditoria
-- ---------------------------------------------------------------------------
-- Solo se inserta y se lee; no se actualiza ni se borra desde la API. El
-- usuario es nullable para poder auditar un login fallido o una accion del
-- sistema. entidad_id es text para admitir tanto ids numericos como claves
-- textuales, y detalle guarda el contexto (por ejemplo, el correo intentado).
-- ---------------------------------------------------------------------------

CREATE TABLE auditoria (
    id          bigserial   PRIMARY KEY,
    usuario_id  bigint      REFERENCES usuarios (id) ON DELETE RESTRICT,
    accion      text        NOT NULL,
    entidad     text        NOT NULL,
    entidad_id  text        NOT NULL,
    detalle     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    ip          inet,
    creado_en   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX auditoria_entidad_entidad_id_idx
    ON auditoria (entidad, entidad_id);

CREATE INDEX auditoria_creado_en_idx
    ON auditoria (creado_en);
